// SpectreScan — one-click export of a scan as a markdown report.
// Pure string building from the scan result, so it is unit-testable
// and runs entirely in the browser: no server, no PDF service. The
// report states the scan time, the score and band, every finding
// with its evidence, and the honesty lines, so a downloaded report
// never reads as an audit.

import type { ScanResult } from "@/lib/engine/types";
import { formatAmount, formatShare, shortAddress } from "@/lib/format";

// Escape user-controlled text for markdown: a token name, finding
// title, detail, or evidence line crafted as [x](https://evil...)
// would otherwise ship as a live link or image in the downloaded
// file, and a previewer that loads remote images would turn it
// into a tracking beacon. The verdict is already stripped of
// markdown server side before it is stored, so it needs no escape.
function mdEscape(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/\[/g, "\\[").replace(/\]/g, "\\]").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

export function buildMarkdownReport(result: ScanResult): string {
  const lines: string[] = [];
  const displayName = result.token.name || result.token.symbol || null;
  const title =
    displayName !== null
      ? `${mdEscape(displayName)}${result.token.name && result.token.symbol ? ` (${mdEscape(result.token.symbol)})` : ""}`
      : result.address;
  lines.push(`# SpectreScan report: ${title}`);
  lines.push("");
  lines.push(`Address: ${result.address}`);
  lines.push(`Score: ${result.score} / 100 (${result.band})`);
  lines.push(`Scanned: ${result.scannedAt}`);
  lines.push(
    `Source: ${result.verificationStatus === "perfect" ? "verified" : result.verificationStatus === "partial" ? "partially verified" : "not verified"}`,
  );
  lines.push("");
  if (result.isEOA) {
    lines.push("This address is a wallet, not a smart contract.");
    lines.push("No token checks ran. The score is 0 because there is");
    lines.push("nothing to score, not because the wallet is safe.");
    lines.push("");
  } else {
    if (result.explanation) {
      lines.push("## Verdict");
      lines.push("");
      lines.push(result.explanation);
      lines.push("");
    }
    lines.push("## Findings");
    lines.push("");
    if (result.findings.length === 0) {
      lines.push("Nothing suspicious turned up in the nine checks.");
      lines.push("");
    }
    for (const f of result.findings) {
      lines.push(`### ${mdEscape(f.title)} (${f.severity}, +${f.weight})`);
      lines.push("");
      lines.push(mdEscape(f.detail));
      lines.push("");
      for (const e of f.evidence) lines.push(`- ${mdEscape(e)}`);
      lines.push("");
    }
    const dossier = result.dossier;
    if (dossier) {
      lines.push("## Dossier");
      lines.push("");
      lines.push(
        `Window: last 20,000 blocks, about 17 hours on BSC${dossier.analysis.complete ? "" : " (partial window)"}.`,
      );
      const pair = dossier.pair;
      if (pair) {
        lines.push(
          `Pair: ${pair.dexId} ${shortAddress(pair.pairAddress)}${pair.priceUsd ? `, price $${pair.priceUsd}` : ""}${pair.liquidity?.usd !== undefined ? `, liquidity $${Math.round(pair.liquidity.usd).toLocaleString()}` : ""}.`,
        );
      } else {
        lines.push("Pair: no trading pair found.");
      }
      const summary = dossier.analysis.summary;
      if (summary) {
        lines.push(
          `Top movers shown: ${summary.holders.length}, ${formatShare(summary.holders.reduce((s, h) => s + (h.share ?? 0), 0))} of supply moved in the window.`,
        );
        lines.push(
          `Total moved: ${formatAmount(summary.totalMoved, result.token.decimals, result.token.symbol)}.`,
        );
      }
      lines.push("");
    }
  }
  lines.push("## What this report is not");
  lines.push("");
  lines.push(
    "SpectreScan is not an audit. Never invest more than you can afford to lose.",
  );
  lines.push(
    "It reads the verified source and public on-chain data; it cannot see hidden behaviour, and it never calls a contract safe.",
  );
  lines.push("");
  lines.push("Generated by SpectreScan: https://spectrescan.onrender.com");
  return lines.join("\n");
}

export function downloadMarkdown(filename: string, text: string): void {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
